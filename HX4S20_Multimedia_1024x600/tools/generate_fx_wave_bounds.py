"""Generate exact quadratic wave boundaries as small combinational LUT cases.

Radii depend only on 28 visible ages, not the raster pixel. Keep true ellipses
while removing the age -> add -> multiply -> subtract critical path. No BRAM.
"""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[1]
lines = ["// Generated by tools/generate_fx_wave_bounds.py; exact integer bounds.",
         "// Combinational case functions, no memory array or block-RAM read.",
         "function [63:0] qin_wave_bounds;", " input [4:0] elapsed;",
         " begin case(elapsed)"]
records = []
for age in range(28):
    radius = 3 * age + 10
    echo = radius - 18
    values = [radius**2, (radius+4)**2,
              echo**2 if age >= 6 else 0, (echo+4)**2 if age >= 6 else 0]
    packed = sum(value << (16*(3-i)) for i, value in enumerate(values))
    lines.append(f"  5'd{age}:qin_wave_bounds=64'h{packed:016x};")
    records.append(dict(scene=1, age=age, bounds=values))
lines += ["  default:qin_wave_bounds=0;", " endcase end", "endfunction",
          "function [31:0] drum_wave_bounds;", " input [4:0] elapsed;",
          " begin case(elapsed)"]
for age in range(28):
    radius = 2 * age + 5
    values = [radius**2, (radius+4)**2]
    lines.append(f"  5'd{age}:drum_wave_bounds=32'h{values[0]:04x}{values[1]:04x};")
    records.append(dict(scene=4, age=age, bounds=values))
lines += ["  default:drum_wave_bounds=0;", " endcase end", "endfunction", ""]
target = root / "rtl/fx_wave_bounds.vh"
target.write_text("\n".join(lines), encoding="ascii")
report = dict(method="exact combinational age-boundary cases; no BRAM", ages=28,
              source_sha256=hashlib.sha256(target.read_bytes()).hexdigest(), records=records)
(root / "sim/fx_wave_bounds_audit.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
print("PASS generated 56 exact age/scene boundary records; integer squared circles, no approximation")
